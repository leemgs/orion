#!/usr/bin/env python3
"""Export measured JSON summaries as LaTeX macros used by the manuscript."""
from __future__ import annotations

import argparse
import json
import statistics
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=Path,
                        default=ROOT / "paper/generated_results.tex")
    args = parser.parse_args()

    cpu = json.loads((ROOT / "code/results/cpu_probe/cpu_hierarchy_summary.json").read_text())
    points = {point["w_mib"]: point for point in cpu["points"]}
    matrix = json.loads((ROOT / "code/results/colab_probe/summary.json").read_text())
    rc_points = [point for point in matrix["points"] if point["sweep"] == "R_C"]
    low = [point["t_total_s"] for point in rc_points if point["r_c"] < 0.5]
    full = [point["t_total_s"] for point in rc_points if point["r_c"] >= 1.0]
    low_ms, full_ms = statistics.mean(low) * 1e3, statistics.mean(full) * 1e3

    # Real GPU (Tesla T4) measurement, Colab CUDA-event timing.
    gpu = json.loads((ROOT / "code/results/colab_probe/tesla_t4_summary.json").read_text())
    g_rc = [p for p in gpu["points"] if p["sweep"] == "R_C"]
    g_rb = [p for p in gpu["points"] if p["sweep"] == "R_B"]
    gpu_cap = statistics.mean(p["t_total_s"] for p in g_rc if p["r_c"] < 0.5) * 1e3
    gpu_res = statistics.mean(p["t_total_s"] for p in g_rc if p["r_c"] >= 1.0) * 1e3
    gpu_io = statistics.mean(p["t_total_s"] for p in g_rb
                             if p["r_b"] is not None and p["r_b"] < 1.0) * 1e3
    gpu_ovl = statistics.mean(p["t_total_s"] for p in g_rb
                              if p["r_b"] is not None and p["r_b"] >= 1.0) * 1e3

    def mean(size: float) -> str:
        return f"{points[size]['lat_ns_mean']:.1f}"

    def sd(size: float) -> str:
        return f"{points[size]['lat_ns_sd']:.1f}"

    macros = {
        "CpuSmallMean": mean(0.5), "CpuSmallSd": sd(0.5),
        "CpuLlcMean": mean(48), "CpuLlcSd": sd(48),
        "CpuBoundaryMean": mean(96), "CpuBoundarySd": sd(96),
        "CpuLargeMean": mean(256), "CpuLargeSd": sd(256),
        "MatrixLowMeanMs": f"{low_ms:.2f}",
        "MatrixFullMeanMs": f"{full_ms:.2f}",
        "MatrixLatencyRatio": f"{low_ms / full_ms:.2f}",
        "GpuDevice": gpu["device"].split(":", 1)[-1],
        "GpuCapacityMs": f"{gpu_cap:.2f}",
        "GpuResidentMs": f"{gpu_res:.2f}",
        "GpuCapacityRatio": f"{gpu_cap / gpu_res:.2f}",
        "GpuIoMeanMs": f"{gpu_io:.2f}",
        "GpuOverlapMeanMs": f"{gpu_ovl:.2f}",
    }
    content = "% Generated by code/experiments/export_paper_results.py; do not edit.\n"
    content += "".join(f"\\newcommand{{\\{name}}}{{{value}}}\n"
                       for name, value in macros.items())
    args.output.write_text(content)
    print(f"wrote {args.output}")


if __name__ == "__main__":
    main()
