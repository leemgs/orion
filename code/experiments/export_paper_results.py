#!/usr/bin/env python3
"""Export measured JSON summaries as LaTeX macros used by the manuscript."""
from __future__ import annotations

import argparse
import json
import statistics
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[2]

# Fixed seed so the reported bootstrap intervals are reproducible from the
# committed raw trials.
BOOTSTRAP_SEED = 20260818
BOOTSTRAP_RESAMPLES = 10000


def bootstrap_mean_ci(samples: list[float], seed: int = BOOTSTRAP_SEED,
                      resamples: int = BOOTSTRAP_RESAMPLES,
                      alpha: float = 0.05) -> tuple[float, float]:
    """Percentile bootstrap CI for the mean of a small trial set.

    This quantifies within-machine trial variability from the committed
    per-trial records; it is not a confidence interval over a hardware
    population (see Methods).
    """
    values = np.asarray(samples, dtype=float)
    rng = np.random.default_rng(seed)
    draws = rng.choice(values, size=(resamples, values.size), replace=True)
    means = draws.mean(axis=1)
    lo, hi = np.quantile(means, [alpha / 2, 1 - alpha / 2])
    return float(lo), float(hi)


def load_cpu_trials() -> dict[float, list[float]]:
    """Group per-trial dependent-load latencies by working-set size (MiB)."""
    path = ROOT / "code/results/cpu_probe/cpu_hierarchy_records.jsonl"
    trials: dict[float, list[float]] = {}
    for line in path.read_text().splitlines():
        line = line.strip()
        if not line:
            continue
        record = json.loads(line)
        w_mib = record["w_bytes"] / (1024 * 1024)
        trials.setdefault(w_mib, []).append(record["lat_per_access_ns"])
    return trials


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=Path,
                        default=ROOT / "paper/generated_results.tex")
    args = parser.parse_args()

    cpu = json.loads((ROOT / "code/results/cpu_probe/cpu_hierarchy_summary.json").read_text())
    points = {point["w_mib"]: point for point in cpu["points"]}
    matrix = json.loads((ROOT / "code/results/colab_probe/summary.json").read_text())
    rc_points = [point for point in matrix["points"] if point["sweep"] == "R_C"]
    low = [point["t_total_s"] for point in rc_points if point["r_c"] < 0.5]
    full = [point["t_total_s"] for point in rc_points if point["r_c"] >= 1.0]
    low_ms, full_ms = statistics.mean(low) * 1e3, statistics.mean(full) * 1e3

    # Real accelerator measurements. The Tesla T4 (CUDA-event timing) is the
    # primary device used in the running text; A100 and TPU v5e provide the
    # cross-accelerator comparison. Order: T4, A100, TPU.
    probe = ROOT / "code/results/colab_probe"
    accel_order = ["accel_tesla-t4.json", "accel_a100.json", "accel_tpu-xla.json"]

    def summarise(path: Path) -> dict:
        data = json.loads(path.read_text())
        rc = [p for p in data["points"] if p["sweep"] == "R_C"]
        cap = statistics.mean(p["t_total_s"] for p in rc if p["r_c"] < 0.5) * 1e3
        res = statistics.mean(p["t_total_s"] for p in rc if p["r_c"] >= 1.0) * 1e3
        rb = [p for p in data["points"] if p["sweep"] == "R_B"]
        io = [p["t_total_s"] for p in rb if p.get("r_b") is not None and p["r_b"] < 1.0]
        ovl = [p["t_total_s"] for p in rb if p.get("r_b") is not None and p["r_b"] >= 1.0]
        return {
            "device": data["device"].split(":", 1)[-1],
            "cap_ms": cap, "res_ms": res, "ratio": cap / res,
            "io_ms": statistics.mean(io) * 1e3 if io else None,
            "ovl_ms": statistics.mean(ovl) * 1e3 if ovl else None,
            "xla": data.get("xla_timing_caveat", False),
        }

    accels = [summarise(probe / f) for f in accel_order if (probe / f).exists()]
    gpu = accels[0]  # Tesla T4 primary
    gpu_cap, gpu_res = gpu["cap_ms"], gpu["res_ms"]
    gpu_io, gpu_ovl = gpu["io_ms"], gpu["ovl_ms"]

    # Cross-accelerator comparison table (device, capacity crossover ratio).
    rows = []
    for a in accels:
        note = "$R_B$ split unreliable (XLA)" if a["xla"] else \
               ("sweep spans $R_B=1$" if a["device"].endswith("T4") else
                "sweep~B compute-bound")
        rows.append(f"{a['device']} & {a['res_ms']:.1f} & {a['cap_ms']:.1f} & "
                    f"{a['ratio']:.2f}$\\times$ & {note} \\\\")
    table = ("% Generated by export_paper_results.py; do not edit.\n"
             "\\begin{tabular}{lrrll}\n\\toprule\n"
             "Accelerator & Resident $T$ (ms) & Cap.-limited $T$ (ms) & "
             "Ratio & Overlap sweep \\\\\n\\midrule\n"
             + "\n".join(rows) +
             "\n\\bottomrule\n\\end{tabular}\n")
    (ROOT / "paper/generated_accel_table.tex").write_text(table)

    def mean(size: float) -> str:
        return f"{points[size]['lat_ns_mean']:.1f}"

    def sd(size: float) -> str:
        return f"{points[size]['lat_ns_sd']:.1f}"

    trials = load_cpu_trials()

    def ci(size: float) -> tuple[str, str]:
        lo, hi = bootstrap_mean_ci(trials[size])
        return f"{lo:.1f}", f"{hi:.1f}"

    small_lo, small_hi = ci(0.5)
    llc_lo, llc_hi = ci(48)
    boundary_lo, boundary_hi = ci(96)
    large_lo, large_hi = ci(256)

    macros = {
        "CpuSmallMean": mean(0.5), "CpuSmallSd": sd(0.5),
        "CpuLlcMean": mean(48), "CpuLlcSd": sd(48),
        "CpuBoundaryMean": mean(96), "CpuBoundarySd": sd(96),
        "CpuLargeMean": mean(256), "CpuLargeSd": sd(256),
        "CpuSmallCiLo": small_lo, "CpuSmallCiHi": small_hi,
        "CpuLlcCiLo": llc_lo, "CpuLlcCiHi": llc_hi,
        "CpuBoundaryCiLo": boundary_lo, "CpuBoundaryCiHi": boundary_hi,
        "CpuLargeCiLo": large_lo, "CpuLargeCiHi": large_hi,
        "MatrixLowMeanMs": f"{low_ms:.2f}",
        "MatrixFullMeanMs": f"{full_ms:.2f}",
        "MatrixLatencyRatio": f"{low_ms / full_ms:.2f}",
        "GpuDevice": gpu["device"].split(":", 1)[-1],
        "GpuCapacityMs": f"{gpu_cap:.2f}",
        "GpuResidentMs": f"{gpu_res:.2f}",
        "GpuCapacityRatio": f"{gpu_cap / gpu_res:.2f}",
        "GpuIoMeanMs": f"{gpu_io:.2f}",
        "GpuOverlapMeanMs": f"{gpu_ovl:.2f}",
        "NumAccel": str(len(accels)),
        "AccelCapRatioMin": f"{min(a['ratio'] for a in accels):.2f}",
        "AccelCapRatioMax": f"{max(a['ratio'] for a in accels):.2f}",
    }
    content = "% Generated by code/experiments/export_paper_results.py; do not edit.\n"
    content += "".join(f"\\newcommand{{\\{name}}}{{{value}}}\n"
                       for name, value in macros.items())
    args.output.write_text(content)
    print(f"wrote {args.output}")


if __name__ == "__main__":
    main()
